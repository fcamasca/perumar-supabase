import { Companies } from '../src/enrollment/EnrollmentPages'
const {client,state}=vi.hoisted(()=>({client:{from:vi.fn(),rpc:vi.fn(),functions:{invoke:vi.fn()}},state:{phase:'authorized',roles:['COORDINADOR_ACADEMICO']}}))
